-- Sample Snowflake slice: SALES_DB.CORE
-- Covers TABLE, STREAM, TASK DAG (+ stream/task/MERGE CDC pattern), DYNAMIC TABLE, VIEW, SQL + JS procedures.

create or replace TABLE SALES_DB.CORE.RAW_ORDERS (
	ORDER_ID NUMBER(38,0) NOT NULL,
	CUSTOMER_ID NUMBER(38,0),
	ORDER_TS TIMESTAMP_NTZ(9),
	AMOUNT NUMBER(12,2),
	STATUS VARCHAR(20) DEFAULT 'NEW',
	PAYLOAD VARIANT,
	LOADED_AT TIMESTAMP_LTZ(9) DEFAULT CURRENT_TIMESTAMP(),
	primary key (ORDER_ID)
) CHANGE_TRACKING = TRUE COMMENT='Orders landed from the OMS';

create or replace TABLE SALES_DB.CORE.RAW_CUSTOMERS (
	CUSTOMER_ID NUMBER(38,0) NOT NULL,
	NAME VARCHAR(200),
	REGION VARCHAR(50),
	CREATED_AT TIMESTAMP_TZ(9)
);

create or replace TABLE SALES_DB.CORE.ORDERS (
	ORDER_ID NUMBER(38,0) NOT NULL,
	CUSTOMER_ID NUMBER(38,0),
	ORDER_TS TIMESTAMP_NTZ(9),
	AMOUNT NUMBER(12,2),
	STATUS VARCHAR(20)
) cluster by (ORDER_TS);

create or replace stream SALES_DB.CORE.RAW_ORDERS_STRM on table SALES_DB.CORE.RAW_ORDERS;

create or replace task SALES_DB.CORE.T_ROOT
	warehouse=ETL_WH
	schedule='USING CRON 0 5 * * * America/New_York'
	as SELECT 1;

create or replace task SALES_DB.CORE.T_MERGE_ORDERS
	warehouse=ETL_WH
	after SALES_DB.CORE.T_ROOT
	when SYSTEM$STREAM_HAS_DATA('SALES_DB.CORE.RAW_ORDERS_STRM')
	as MERGE INTO SALES_DB.CORE.ORDERS t
USING SALES_DB.CORE.RAW_ORDERS_STRM s
ON t.ORDER_ID = s.ORDER_ID
WHEN MATCHED AND s.METADATA$ACTION = 'DELETE' AND s.METADATA$ISUPDATE = FALSE THEN DELETE
WHEN MATCHED AND s.METADATA$ACTION = 'INSERT' THEN UPDATE SET t.CUSTOMER_ID = s.CUSTOMER_ID, t.ORDER_TS = s.ORDER_TS, t.AMOUNT = s.AMOUNT, t.STATUS = s.STATUS
WHEN NOT MATCHED AND s.METADATA$ACTION = 'INSERT' THEN INSERT (ORDER_ID, CUSTOMER_ID, ORDER_TS, AMOUNT, STATUS) VALUES (s.ORDER_ID, s.CUSTOMER_ID, s.ORDER_TS, s.AMOUNT, s.STATUS);

create or replace task SALES_DB.CORE.T_REFRESH_STATS
	warehouse=ETL_WH
	after SALES_DB.CORE.T_MERGE_ORDERS
	as CALL SALES_DB.CORE.SP_REFRESH_STATS(7);

create or replace dynamic table SALES_DB.CORE.DT_ORDER_ENRICHED(
	ORDER_ID, CUSTOMER_NAME, REGION, ORDER_DAY, AMOUNT, AMOUNT_BAND
) target_lag = '15 minutes' refresh_mode = AUTO initialize = ON_CREATE warehouse = ETL_WH
 as
SELECT o.ORDER_ID, c.NAME, c.REGION, TO_DATE(o.ORDER_TS), o.AMOUNT,
       IFF(o.AMOUNT >= 1000, 'HIGH', 'LOW')
FROM SALES_DB.CORE.ORDERS o
LEFT JOIN SALES_DB.CORE.RAW_CUSTOMERS c ON c.CUSTOMER_ID = o.CUSTOMER_ID
QUALIFY ROW_NUMBER() OVER (PARTITION BY o.ORDER_ID ORDER BY o.ORDER_TS DESC) = 1;

create or replace view SALES_DB.CORE.DIM_CUSTOMER(CUSTOMER_ID, NAME, REGION, CREATED_DAY) as
SELECT CUSTOMER_ID, NAME, NVL(REGION, 'UNKNOWN'), TO_DATE(CREATED_AT) FROM SALES_DB.CORE.RAW_CUSTOMERS;

create or replace secure view SALES_DB.CORE.FCT_DAILY_SALES as
SELECT ORDER_DAY, REGION, SUM(AMOUNT) AS REVENUE, COUNT(*) AS ORDERS, DIV0(SUM(AMOUNT), COUNT(*)) AS AOV
FROM SALES_DB.CORE.DT_ORDER_ENRICHED
GROUP BY ORDER_DAY, REGION;

CREATE OR REPLACE PROCEDURE SALES_DB.CORE.SP_REFRESH_STATS("DAYS" NUMBER(38,0))
RETURNS VARCHAR(16777216)
LANGUAGE SQL
EXECUTE AS OWNER
AS '
BEGIN
  DELETE FROM SALES_DB.CORE.ORDERS WHERE ORDER_TS < DATEADD(day, -1 * :DAYS * 100, CURRENT_TIMESTAMP());
  INSERT INTO SALES_DB.CORE.ORDERS SELECT ORDER_ID, CUSTOMER_ID, ORDER_TS, AMOUNT, ''REPLAY'' FROM SALES_DB.CORE.RAW_ORDERS WHERE STATUS = ''REPLAY'';
  RETURN ''ok'';
END;
';

CREATE OR REPLACE PROCEDURE SALES_DB.CORE.SP_JS_AUDIT(TBL VARCHAR)
RETURNS FLOAT
LANGUAGE JAVASCRIPT
EXECUTE AS CALLER
AS $$
  var rs = snowflake.execute({sqlText: "SELECT COUNT(*) FROM " + TBL});
  rs.next();
  return rs.getColumnValue(1);
$$;
