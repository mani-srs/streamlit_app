"""Agent 4 - md_plan: migration plan markdown with a deterministic risk register.
gen (planner model, deterministic fallback) -> eval (deterministic + evaluator model) -> HITL.
"""
from __future__ import annotations

import re

from agents.cd_codegen.agent import map_all
from agents.common import in_scope_objects, need
from core import llm
from core.graph import RunContext
from core.nodes import build_gen_eval_hitl, feedback_notes, issues_for, verdict_from
from core.prompts import PromptParts, assemble, post_check, strip_fences
from core.schemas import EvalResult, GenResult, Issue, Severity
from core.state import RunState

STAGE = "md_plan"
SECTIONS = ["## 1. Scope", "## 2. Object mapping", "## 3. Risk register", "## 4. Cutover order", "## 5. Validation", "## 6. Open questions"]

TARGETS = {"TABLE": "UC Delta table", "VIEW": "UC view", "DYNAMIC_TABLE": "DLT materialized view (@dlt.table)",
           "STREAM": "Delta Change Data Feed + DLT streaming read", "TASK": "Databricks Job task",
           "PROCEDURE": "Databricks notebook"}

RISKS = [  # (regex over DDL, risk id, description, mitigation)
    (r"\bVARIANT\b|\bOBJECT\b|\bARRAY\b|:\w+::", "R-VARIANT", "semi-structured data (VARIANT/OBJECT/ARRAY, path access)",
     "Databricks VARIANT (DBR 15.3+); verify path/cast semantics"),
    (r"\bLATERAL\s+FLATTEN\b|\bFLATTEN\s*\(", "R-FLATTEN", "FLATTEN", "rewrite with explode/posexplode/variant_explode"),
    (r"\bQUALIFY\b", "R-QUALIFY", "QUALIFY", "supported in Databricks SQL; verify NULL ordering (NULLS FIRST/LAST)"),
    (r"\bTIMESTAMP_(?:LTZ|TZ)\b|\bCONVERT_TIMEZONE\b|\bCURRENT_TIMESTAMP\b|\bSYSDATE\b", "R-TZ", "time zone semantics",
     "set spark.sql.session.timeZone to the Snowflake account TIMEZONE; TZ offsets are not stored"),
    (r"\bCOLLATE\b", "R-COLLATION", "collations", "Databricks collations differ; review comparisons"),
    (r"\bAUTOINCREMENT\b|\bIDENTITY\b|\bSEQUENCE\b|\.NEXTVAL\b", "R-IDENTITY", "identity/sequence columns",
     "BIGINT GENERATED BY DEFAULT AS IDENTITY; gaps and ordering differ"),
    (r"\bTARGET_LAG\b", "R-LAG", "dynamic table freshness (TARGET_LAG)", "schedule pipeline refresh at the lag interval"),
    (r"\bLANGUAGE\s+(?:JAVASCRIPT|PYTHON|JAVA|SCALA)\b", "R-PROC", "non-SQL stored procedures", "AI translation + mandatory review"),
    (r"\bSECURE\s+VIEW\b|\bMASKING\s+POLICY\b|\bROW\s+ACCESS\s+POLICY\b", "R-SEC", "secure views / policies",
     "UC grants, row filters and column masks"),
    (r"\bSYSTEM\$STREAM_HAS_DATA\b", "R-WHEN", "task WHEN conditions", "streaming reads are no-ops when empty"),
    (r"\bEXECUTE\s+AS\s+CALLER\b", "R-CALLER", "caller's-rights procedures", "job run-as principal privileges"),
]


def risk_register(objs: list[dict]) -> list[dict]:
    out = []
    for rx, rid, what, fix in RISKS:
        hit = [o["id"] for o in objs if re.search(rx, o.get("ddl", ""), re.I)]
        if hit:
            out.append({"id": rid, "risk": what, "objects": hit, "mitigation": fix})
    return out


def skeleton(state: RunState) -> tuple[str, dict]:
    objs = in_scope_objects(state)
    g = need(state, "discovery")["graph"]
    frags, slots, mctx, job_files, _ = map_all(state)
    origin = {}
    for f in frags:
        for nid in [f.node_id, *f.collapses]:
            origin.setdefault(nid, f.origin)
    risks = risk_register(objs)
    s = state.slice
    lines = [f"# Migration plan: {s.slice_id} -> Databricks", "", SECTIONS[0],
             f"- Slice: `{s.slice_id}`, {len(objs)} objects: " +
             ", ".join(f"{t}={sum(o['type'] == t for o in objs)}" for t in TARGETS if any(o["type"] == t for o in objs)),
             f"- Target catalog: `{mctx.mapper.catalog_override or (objs[0]['database'].lower() if objs else '')}`",
             f"- Deterministic coverage: {sum(v == 'MAPPED' for v in origin.values())}/{len(origin)} nodes MAPPED, "
             f"{len(slots.slots)} AI slot(s)", "", SECTIONS[1], "",
             "| Snowflake object | Type | Databricks target | Name | Origin |", "|---|---|---|---|---|"]
    for o in objs:
        tgt = TARGETS[o["type"]]
        if any(p["stream"] == o["id"] or p["task"] == o["id"] for p in g["patterns"]):
            tgt = "collapsed into DLT apply_changes (CDC)"
        elif any(p["target"] == o["id"] for p in g["patterns"]):
            tgt = "DLT streaming table (apply_changes target)"
        lines.append(f"| `{o['id']}` | {o['type']} | {tgt} | `{mctx.mapper.target(o['id'])}` | {origin.get(o['id'], '-')} |")
    lines += ["", SECTIONS[2], "", "| ID | Risk | Objects | Mitigation |", "|---|---|---|---|"]
    lines += [f"| {r['id']} | {r['risk']} | {', '.join(f'`{x}`' for x in r['objects'])} | {r['mitigation']} |" for r in risks] or ["| - | none detected | | |"]
    lines += ["", SECTIONS[3], "", "1. Create UC tables (`ddl/01_tables.sql`), enable Change Data Feed where streams exist.",
              "2. Backfill historical data (out of scope for code generation).",
              "3. Deploy the DLT pipeline (`pipeline/bronze|silver|gold.py`) and run a full refresh.",
              "4. Create UC views (`ddl/02_views.sql`).",
              f"5. Create Jobs ({', '.join(f'`{k}`' for k in job_files) or 'none'}), paused; enable after parity passes.",
              "", "Dependency order: " + " -> ".join(f"`{i.split('.')[-1]}`" for i in g["order"] if i in {o['id'] for o in objs}),
              "", SECTIONS[4], "", "- Deterministic judges STR/DET/SEM/LIN/POL/SNF on all generated code.",
              "- Parity manifest: row counts, column null counts, min/max per column, Snowflake vs Databricks.",
              "", SECTIONS[5], ""]
    ext = [n["id"] for n in g["nodes"] if not n["in_scope"]]
    qs = [f"- Upstream `{x}` is outside the slice: migrate it or map to an existing UC table?" for x in ext]
    qs += [f"- Confirm Spark session time zone for {', '.join(r['objects'])}." for r in risks if r["id"] == "R-TZ"]
    lines += qs or ["- none"]
    return "\n".join(lines), {"risks": risks, "origin": origin}


PLANNER = ("You are a principal data architect writing a Snowflake -> Databricks migration plan. Improve the draft plan: "
           "keep every section heading exactly as given, keep every table row, add concrete, specific guidance. "
           "Return the full plan as GitHub markdown only.")
EVALUATOR = ("You review Snowflake -> Databricks migration plans. Return ONLY JSON: "
             '{"verdict":"pass|revise|fail","confidence":0-1,"summary":"...","issues":[{"id":"PLAN-1","severity":"info|warn|error",'
             '"ref":"object:<SNOWFLAKE_FQN> or file:plan.md","message":"...","suggested_fix":"..."}]}')


def gen(ctx: RunContext, state: RunState, feedback) -> GenResult:
    draft, meta = skeleton(state)
    notes, hard = feedback_notes(feedback, issues_for(state, STAGE))
    meta["source"] = "deterministic"
    if ctx.llm_enabled:
        try:
            msgs = assemble(PromptParts(system=PLANNER, task="Rewrite and enrich this plan draft.", context=draft,
                                        feedback=notes, hard_constraints=hard))
            txt = strip_fences(llm.complete(ctx, "planner", msgs, stage=STAGE).text)
            if all(s in txt for s in SECTIONS):
                draft, meta["source"] = txt, "planner"
            else:
                meta["planner_rejected"] = "missing required sections"
        except llm.LlmUnavailable as e:
            meta["planner_error"] = str(e)
    elif notes:
        draft += "\n\n## Reviewer notes\n" + "\n".join(f"- {n}" for n in notes)
    meta["hard_violations"] = post_check(draft, hard)
    return GenResult(artifact=draft, meta=meta)


def evaluate(ctx: RunContext, state: RunState, g: GenResult) -> EvalResult:
    issues = []
    for s in SECTIONS:
        if s not in g.artifact:
            issues.append(Issue(f"PLAN-SEC-{len(issues)}", Severity.ERROR, "file:plan.md", f"missing section {s}"))
    for o in in_scope_objects(state):
        if o["id"] not in g.artifact:
            issues.append(Issue(f"PLAN-OBJ-{len(issues)}", Severity.WARN, f"object:{o['id']}", "object not mentioned in plan"))
    for v in g.meta.get("hard_violations", []):
        issues.append(Issue(f"PLAN-HC-{len(issues)}", Severity.ERROR, "file:plan.md", v))
    summary = "deterministic checks"
    if ctx.llm_enabled:
        try:
            res = llm.complete(ctx, "evaluator", assemble(PromptParts(system=EVALUATOR, task="Review this plan.", context=g.artifact)),
                               stage=STAGE, json_mode=True)
            model_eval = EvalResult.from_dict(res.parsed)
            issues += [Issue(f"M-{i.id}", i.severity, i.ref, i.message, i.suggested_fix) for i in model_eval.issues]
            summary = model_eval.summary or summary
        except Exception as e:  # evaluator failure never blocks; recorded as info
            issues.append(Issue("PLAN-EVAL", Severity.INFO, "file:plan.md", f"model evaluator unavailable: {e}"))
    return verdict_from(issues, 0.8, summary)


def save(ctx, g: GenResult, it: int) -> None:
    ctx.put("plan.md", g.artifact, it)


def finalize(ctx, state, g: GenResult, e) -> dict:
    return {"plan_md": g.artifact, "risks": g.meta.get("risks", []), "source": g.meta.get("source")}


node = build_gen_eval_hitl(STAGE, gen, evaluate, finalize, save, max_iters=2)
