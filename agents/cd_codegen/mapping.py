"""MapperRegistry: Snowflake object -> Databricks fragment(s). Deterministic.

Origins
  MAPPED  fully deterministic output
  HYBRID  deterministic scaffold + __PENDING_n__ slots filled by the translator model
  AI      whole body delegated to the translator model (scaffold still deterministic)

Every fragment carries a node marker ("NODE: <id> | <TYPE> | <ORIGIN>") used by STR001.
"""
from __future__ import annotations

import json
import re
from dataclasses import asdict, dataclass, field

from converters.cron import to_quartz
from converters.dialect import NameMapper, TranspileError, transpile
from converters.ddl_parser import split_statements
from converters.sqlscan import split_fqn, strip_comments
from converters.types import map_type
from core.schemas import Origin

PENDING_FMT = "__PENDING_{}__"
PENDING_RX = re.compile(r"__PENDING_(\d+)__")
_EXPR_MAPPER = NameMapper("DB", "SCHEMA")  # for standalone expressions (no table refs)


@dataclass
class Slot:
    idx: int
    node_id: str
    kind: str  # sql_query | sql_statement | procedure | task_body | projection
    source: str
    source_lang: str
    target: str  # what to emit
    instructions: str = ""


@dataclass
class Fragment:
    node_id: str
    obj_type: str
    kind: str  # ddl_table | ddl_view | dlt | notebook | job_task
    origin: str
    file: str
    code: str
    target: str = ""
    collapses: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)  # (rule_hint, message) rendered as "HINT|msg"
    job_task: dict | None = None

    def to_dict(self):
        return asdict(self)


class SlotAllocator:
    def __init__(self) -> None:
        self.slots: list[Slot] = []

    def new(self, **kw) -> str:
        s = Slot(idx=len(self.slots), **kw)
        self.slots.append(s)
        return PENDING_FMT.format(s.idx)


def marker(prefix: str, node_id: str, obj_type: str, origin: str, extra: str = "") -> str:
    return f"{prefix} NODE: {node_id} | {obj_type} | {origin}" + (f" | {extra}" if extra else "")


def pyname(fqn_target: str) -> str:
    return "n_" + re.sub(r"\W", "_", fqn_target.split(".")[-1].lower())


def py_triple(sql: str) -> str:
    return '"""\n' + sql.replace("\\", "\\\\").replace('"""', '\\"\\"\\"') + '\n"""'


def bq(col: str) -> str:
    return col if re.fullmatch(r"[A-Za-z_]\w*", col) else "`" + col.replace("`", "``") + "`"


def sql_lit(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


@dataclass
class MapCtx:
    mapper: NameMapper
    slots: SlotAllocator
    objects: dict  # id -> obj
    graph: dict
    cdc: dict  # target id -> pattern
    collapsed: dict  # stream/task id -> pattern id
    cdf_sources: set  # tables needing Change Data Feed
    name_map_text: str = ""


def _col_defs(o: dict, notes: list[str]) -> list[str]:
    defs = []
    for c in o["columns"]:
        dbx, risk = map_type(c["type"])
        if risk:
            notes.append(f"SEM004|{c['name']}: {c['type']} -> {dbx}: {risk}")
        d = f"  {bq(c['name'])} {dbx}"
        if c.get("identity"):
            d = f"  {bq(c['name'])} BIGINT GENERATED BY DEFAULT AS IDENTITY"
            notes.append(f"SEM004|{c['name']}: AUTOINCREMENT/IDENTITY -> BIGINT identity (gaps/ordering differ)")
        if not c["nullable"]:
            d += " NOT NULL"
        if c.get("default") and not c.get("identity"):
            try:
                d += " DEFAULT " + transpile(f"SELECT {c['default']}", _EXPR_MAPPER, pretty=False).sql[7:]
            except Exception:
                notes.append(f"SEM001|{c['name']}: DEFAULT {c['default']} not convertible; dropped")
        if c.get("collation"):
            notes.append(f"SEM004|{c['name']}: COLLATE '{c['collation']}' not preserved (Databricks collations differ)")
        if c.get("comment"):
            d += f" COMMENT {sql_lit(c['comment'])}"
        defs.append(d)
    return defs




def _pk(o: dict) -> list[str]:
    cols = [c["name"] for c in o["columns"] if c.get("primary_key")]
    for con in o.get("constraints", []):
        m = re.search(r"PRIMARY\s+KEY\s*\(([^)]*)\)", con, re.I)
        if m:
            cols += [split_fqn(x)[0] if not x.strip().startswith('"') else x.strip().strip('"') for x in m.group(1).split(",")]
    return list(dict.fromkeys(cols))


# ------------------------------------------------------------------ TABLE
def map_table(o: dict, ctx: MapCtx) -> list[Fragment]:
    tgt = ctx.mapper.target(o["id"])
    notes: list[str] = []
    if o.get("query") and not o["columns"]:  # CTAS
        return [_ctas(o, ctx, tgt)]
    defs = _col_defs(o, notes)
    props = {}
    if o["id"] in ctx.cdf_sources or o.get("change_tracking"):
        props["delta.enableChangeDataFeed"] = "true"
    if any(c.get("default") for c in o["columns"]):
        props["delta.feature.allowColumnDefaults"] = "supported"
    pk = _pk(o)
    nn = {c["name"] for c in o["columns"] if not c["nullable"]}
    cluster = [re.sub(r'^"|"$', "", c.strip()).upper() if not c.strip().startswith('"') else c.strip().strip('"')
               for c in o.get("cluster_by", [])]
    if any(not re.fullmatch(r"[\w$]+", c) for c in cluster):
        notes.append("SEM004|CLUSTER BY uses expressions; Databricks liquid clustering needs plain columns - dropped")
        cluster = []
    if o.get("transient"):
        notes.append("INFO|TRANSIENT table: no Fail-safe equivalent; set delta.deletedFileRetentionDuration if needed")

    if o["id"] in ctx.cdc:  # DLT owns this table as the apply_changes target
        schema = ", ".join(d.strip() for d in defs)
        args = [f'    name="{tgt}"', f"    schema={py_triple(schema)}"]
        if o.get("comment"):
            args.append(f"    comment={json.dumps(o['comment'])}")
        if cluster:
            args.append(f"    cluster_by={json.dumps(cluster)}")
        if props:
            args.append(f"    table_properties={json.dumps(props)}")
        code = "\n".join([marker("#", o["id"], "TABLE", Origin.MAPPED.value, "DLT streaming table (CDC target)"),
                          "dlt.create_streaming_table(", ",\n".join(args), ")"])
        return [Fragment(o["id"], "TABLE", "dlt", Origin.MAPPED.value, "pipeline", code, tgt, notes=notes)]

    body = list(defs)
    if pk:
        if all(c in nn for c in pk):
            body.append(f"  CONSTRAINT {tgt.split('.')[-1]}_pk PRIMARY KEY ({', '.join(bq(c) for c in pk)})")
        else:
            notes.append("SEM001|PRIMARY KEY on nullable columns dropped (UC requires NOT NULL)")
    lines = [marker("--", o["id"], "TABLE", Origin.MAPPED.value), f"CREATE TABLE IF NOT EXISTS {tgt} (",
             ",\n".join(body), ")", "USING DELTA"]
    if cluster:
        lines.append(f"CLUSTER BY ({', '.join(bq(c) for c in cluster)})")
    if o.get("comment"):
        lines.append(f"COMMENT {sql_lit(o['comment'])}")
    if props:
        lines.append("TBLPROPERTIES (" + ", ".join(f"'{k}' = '{v}'" for k, v in props.items()) + ")")
    return [Fragment(o["id"], "TABLE", "ddl_table", Origin.MAPPED.value, "ddl/01_tables.sql",
                     "\n".join(lines) + ";", tgt, notes=notes)]


def _ctas(o, ctx, tgt) -> Fragment:
    q, origin = _query_or_slot(o, o["query"], ctx)
    code = "\n".join([marker("--", o["id"], "TABLE", origin, "CTAS"), f"CREATE TABLE IF NOT EXISTS {tgt} AS", q + ";"])
    return Fragment(o["id"], "TABLE", "ddl_table", origin, "ddl/01_tables.sql", code, tgt)


def _query_or_slot(o: dict, query: str, ctx: MapCtx, pretty=True) -> tuple[str, str]:
    try:
        return transpile(query, ctx.mapper, pretty=pretty).sql, Origin.MAPPED.value
    except TranspileError as e:
        ph = ctx.slots.new(node_id=o["id"], kind="sql_query", source=query, source_lang="Snowflake SQL",
                           target="a single Databricks SQL SELECT statement (no trailing semicolon)",
                           instructions=f"Deterministic transpile failed: {e}")
        return ph, Origin.HYBRID.value


# ------------------------------------------------------------------ VIEW
def map_view(o: dict, ctx: MapCtx) -> list[Fragment]:
    tgt = ctx.mapper.target(o["id"])
    q, origin = _query_or_slot(o, o["query"], ctx)
    notes = []
    if o.get("secure"):
        notes.append("INFO|SECURE view: enforce with UC grants / row filters / column masks")
    if o.get("materialized"):
        notes.append("INFO|MATERIALIZED view mapped to a UC view; consider a DLT materialized view")
    cols = f" ({', '.join(bq(c) for c in o['column_aliases'])})" if o.get("column_aliases") else ""
    lines = [marker("--", o["id"], "VIEW", origin), f"CREATE OR REPLACE VIEW {tgt}{cols}"]
    if o.get("comment"):
        lines.append(f"COMMENT {sql_lit(o['comment'])}")
    lines += ["AS", q + ";"]
    return [Fragment(o["id"], "VIEW", "ddl_view", origin, "ddl/02_views.sql", "\n".join(lines), tgt, notes=notes)]


# ------------------------------------------------------------------ DYNAMIC TABLE
def map_dynamic_table(o: dict, ctx: MapCtx) -> list[Fragment]:
    tgt = ctx.mapper.target(o["id"])
    q, origin = _query_or_slot(o, o["query"], ctx)
    notes = [f"SNF001|TARGET_LAG {o.get('target_lag')!r} -> pipeline trigger schedule (see jobs/pipeline_refresh.json)"]
    if o.get("refresh_mode") == "FULL":
        notes.append("INFO|REFRESH_MODE=FULL: DLT materialized view recomputes as needed (Enzyme may incrementalize)")
    args = [f'name="{tgt}"']
    if o.get("comment"):
        args.append(f"comment={json.dumps(o['comment'])}")
    cl = [c.strip().strip('"') for c in o.get("cluster_by", []) if re.fullmatch(r'"?[\w$]+"?', c.strip())]
    if cl:
        args.append(f"cluster_by={json.dumps(cl)}")
    ret = f"spark.sql({py_triple(q)})"
    if o.get("column_aliases"):
        ret += f".toDF({', '.join(json.dumps(c) for c in o['column_aliases'])})"
    code = "\n".join([
        marker("#", o["id"], "DYNAMIC_TABLE", origin, f"TARGET_LAG={o.get('target_lag')}"),
        f"@dlt.table({', '.join(args)})",
        f"def {pyname(tgt)}():",
        f"    return {ret}",
    ])
    return [Fragment(o["id"], "DYNAMIC_TABLE", "dlt", origin, "pipeline", code, tgt, notes=notes)]


# ------------------------------------------------------------------ STREAM (standalone)
def map_stream(o: dict, ctx: MapCtx) -> list[Fragment]:
    if o["id"] in ctx.collapsed:
        return []
    src = ctx.mapper.target(o["source"])
    view = o["name"].lower()
    filt = "_change_type = 'insert'" if (o.get("append_only") or o.get("insert_only")) else "_change_type != 'update_preimage'"
    notes = ["INFO|STREAM -> Delta Change Data Feed streaming read; offsets are tracked by the DLT checkpoint"]
    if o.get("show_initial_rows"):
        notes.append("SEM001|SHOW_INITIAL_ROWS=TRUE -> use option startingVersion=0")
    opt = '.option("startingVersion", 0)' if o.get("show_initial_rows") else ""
    code = "\n".join([
        marker("#", o["id"], "STREAM", Origin.MAPPED.value, f"CDF on {src}"),
        f'@dlt.view(name="{view}")',
        f"def {pyname(view)}():",
        f'    return (spark.readStream.option("readChangeFeed", "true"){opt}.table("{src}")',
        f'            .filter("{filt}"))',
    ])
    return [Fragment(o["id"], "STREAM", "dlt", Origin.MAPPED.value, "pipeline", code, view, notes=notes)]


# ------------------------------------------------------------------ CDC pattern
def map_cdc(p: dict, ctx: MapCtx) -> list[Fragment]:
    tgt = ctx.mapper.target(p["target"])
    src = ctx.mapper.target(p["source"])
    stream = ctx.objects[p["stream"]]
    view = stream["name"].lower()
    notes = [f"INFO|collapsed STREAM {p['stream']} + TASK {p['task']} + MERGE into one apply_changes"]
    origin = Origin.MAPPED.value
    proj = ""
    if p["columns"]:
        exprs = []
        for c, v in zip(p["columns"], p["values"]):
            if re.fullmatch(r'"?[\w$]+"?', v) and v.strip('"').upper() == c.upper():
                exprs.append(bq(c))
            else:
                try:
                    e = transpile(f"SELECT {v}", ctx.mapper, pretty=False).sql[7:]
                    exprs.append(f"{e} AS {bq(c)}")
                except TranspileError:
                    exprs.append(ctx.slots.new(node_id=p["id"], kind="projection", source=f"{v} AS {c}",
                                               source_lang="Snowflake SQL expression",
                                               target="one Spark SQL expression with alias (e.g. `expr AS col`)"))
                    origin = Origin.HYBRID.value
        exprs += ["_change_type", "_commit_version"]
        proj = "\n            .selectExpr(" + ", ".join(json.dumps(x) for x in exprs) + ")"
    filt = "_change_type = 'insert'" if p["append_only"] else "_change_type != 'update_preimage'"
    keys = p["keys"] or [ctx.slots.new(node_id=p["id"], kind="projection", source=ctx.objects[p["task"]]["body"],
                                       source_lang="Snowflake MERGE", target="a JSON list of key column names")]
    if not p["keys"]:
        origin = Origin.HYBRID.value
    key_txt = json.dumps(keys) if p["keys"] else keys[0]
    lines = [
        marker("#", p["id"], "STREAM+TASK+MERGE", origin, f"collapses {p['stream']}, {p['task']}"),
        marker("#", p["stream"], "STREAM", origin, f"collapsed into {p['id']}"),
        marker("#", p["task"], "TASK", origin, f"MERGE body collapsed into {p['id']}"),
        f'@dlt.view(name="{view}")',
        f"def {pyname(view)}():",
        f'    return (spark.readStream.option("readChangeFeed", "true").table("{src}")',
        f'            .filter("{filt}"){proj})',
        "",
        "dlt.apply_changes(",
        f'    target="{tgt}",',
        f'    source="{view}",',
        f"    keys={key_txt},",
        '    sequence_by=F.col("_commit_version"),',
    ]
    if p["has_delete"]:
        lines.append("    apply_as_deletes=F.expr(\"_change_type = 'delete'\"),")
    lines += ['    except_column_list=["_change_type", "_commit_version"],', "    stored_as_scd_type=1,", ")"]
    return [Fragment(p["id"], "STREAM+TASK+MERGE", "dlt", origin, "pipeline", "\n".join(lines), tgt,
                     collapses=[p["stream"], p["task"]], notes=notes)]


# ------------------------------------------------------------------ TASK
_CALL_RX = re.compile(r"^\s*CALL\s+(?P<fqn>[^\s(]+)\s*\((?P<args>.*)\)\s*;?\s*$", re.I | re.S)


def map_task(o: dict, ctx: MapCtx) -> list[Fragment]:
    key = o["name"].lower()
    deps = [{"task_key": ctx.objects[a]["name"].lower()} for a in o.get("after", []) if a in ctx.objects]
    notes = []
    missing = [a for a in o.get("after", []) if a not in ctx.objects]
    if missing:
        notes.append(f"LIN001|predecessor task(s) outside the slice dropped from depends_on: {', '.join(missing)}")
    if o.get("when"):
        if "SYSTEM$STREAM_HAS_DATA" in o["when"].upper():
            hint = "INFO" if o["id"] in ctx.collapsed else "SNF002"
            notes.append(f"{hint}|WHEN SYSTEM$STREAM_HAS_DATA -> streaming/CDF read is a no-op when empty")
        else:
            notes.append(f"SNF002|WHEN {o['when']} has no direct Jobs equivalent; add a condition_task")
    origin = Origin.MAPPED.value
    code = ""
    if o["id"] in ctx.collapsed:
        task = {"task_key": key, "pipeline_task": {"pipeline_id": "${PIPELINE_ID}", "full_refresh": False}}
        file = ""
    else:
        cm = _CALL_RX.match(o.get("body", ""))
        proc_id = ctx.mapper.resolve(split_fqn(cm.group("fqn"))) if cm else None
        if cm and proc_id in ctx.objects:
            proc = ctx.objects[proc_id]
            vals = [v.strip() for v in re.split(r",(?![^()]*\))", cm.group("args")) if v.strip()]
            params = {a["name"]: v.strip("'") for a, v in zip(proc.get("args", []), vals)}
            task = {"task_key": key, "notebook_task": {"notebook_path": "${NOTEBOOK_ROOT}/" + _proc_nb(proc),
                                                      "base_parameters": params}}
            file = ""
        else:
            nb = f"notebooks/task_{key}.sql"
            try:
                body = transpile(o["body"], ctx.mapper).sql
            except TranspileError as e:
                body = ctx.slots.new(node_id=o["id"], kind="task_body", source=o["body"], source_lang="Snowflake SQL",
                                     target="Databricks SQL statement(s) separated by ';'",
                                     instructions=f"Deterministic transpile failed: {e}")
                origin = Origin.HYBRID.value
            code = "\n".join(["-- Databricks notebook source", marker("--", o["id"], "TASK", origin), body + ";"])
            task = {"task_key": key, "notebook_task": {"notebook_path": "${NOTEBOOK_ROOT}/" + nb[:-4],
                                                      "warehouse_id": "${SQL_WAREHOUSE_ID}"}}
            file = nb
    task["description"] = marker("", o["id"], "TASK", origin).strip()
    if deps:
        task["depends_on"] = deps
    return [Fragment(o["id"], "TASK", "job_task" if not file else "notebook", origin, file or "jobs", code,
                     key, notes=notes, job_task=task)]


def build_jobs(objects: dict, task_frags: list[Fragment], ctx: MapCtx) -> tuple[dict[str, str], list[str]]:
    """Group task fragments into one Job per task-DAG root. Returns files, notes."""
    tasks = {f.node_id: f for f in task_frags if f.job_task}
    parent = {tid: [a for a in objects[tid].get("after", []) if a in tasks] for tid in tasks}

    def root(t, seen=()):
        ps = parent.get(t, [])
        return t if not ps or t in seen else root(ps[0], seen + (t,))

    groups: dict[str, list[str]] = {}
    for tid in sorted(tasks):
        groups.setdefault(root(tid), []).append(tid)
    files, notes = {}, []
    for r, members in groups.items():
        ro = objects[r]
        job = {"name": f"{ro['schema'].lower()}_{ro['name'].lower()}",
               "description": f"Migrated Snowflake task DAG rooted at {r}",
               "max_concurrent_runs": 1 if not ro.get("allow_overlapping") else 5,
               "tasks": [tasks[m].job_task for m in members]}
        q, risk = to_quartz(ro.get("schedule"))
        if q:
            job["schedule"] = dict(q, pause_status="PAUSED")
        if risk:
            notes.append(f"SNF003|{r}: {risk}")
        files[f"jobs/{job['name']}.json"] = json.dumps(job, indent=2)
    return files, notes


# ------------------------------------------------------------------ PROCEDURE
_SCRIPTING = re.compile(r"\b(DECLARE|LET|IF|ELSEIF|FOR|WHILE|REPEAT|LOOP|EXCEPTION|CURSOR|RESULTSET|EXECUTE\s+IMMEDIATE|RETURN\s+TABLE)\b", re.I)


def _proc_nb(p: dict) -> str:
    return f"notebooks/proc_{p['name'].lower()}"


def map_procedure(o: dict, ctx: MapCtx) -> list[Fragment]:
    base = _proc_nb(o)
    widgets = [f'dbutils.widgets.text("{a["name"]}", {json.dumps(a.get("default") or "")})' for a in o.get("args", [])]
    reads = [f'{a["name"]} = dbutils.widgets.get("{a["name"]}")' for a in o.get("args", [])]
    notes = []
    if o.get("execute_as") == "CALLER":
        notes.append("INFO|EXECUTE AS CALLER -> runs as the job run-as principal; review privileges")
    body = strip_comments(o.get("body", "")).strip()
    if not body:
        notes.append("SRC001|procedure body is empty in GET_DDL - bodies are only visible to a role that owns the "
                     "procedure; re-extract with the owning role")
        code = "\n".join(["-- Databricks notebook source", marker("--", o["id"], "PROCEDURE", Origin.MAPPED.value, "EMPTY SOURCE"),
                          "-- Source body not visible to the extracting role; nothing to convert."])
        return [Fragment(o["id"], "PROCEDURE", "notebook", Origin.MAPPED.value, base + ".sql", code, base, notes=notes)]
    plain_sql = o.get("language") == "SQL"
    stmts = []
    if plain_sql:
        inner = re.sub(r"^\s*BEGIN\b", "", body, flags=re.I)
        inner = re.sub(r"\bEND\s*;?\s*$", "", inner, flags=re.I).strip()
        if _SCRIPTING.search(inner) or not inner:
            plain_sql = False
        else:
            stmts = split_statements(inner)
    if plain_sql:
        out, origin = [], Origin.MAPPED.value
        for s in stmts:
            if re.match(r"^\s*RETURN\b", s, re.I):
                out.append(f"-- {s.strip()}  (RETURN value: surface via dbutils.notebook.exit in a wrapper if needed)")
                continue
            try:
                out.append(transpile(s, ctx.mapper).sql + ";")
            except TranspileError as e:
                out.append(ctx.slots.new(node_id=o["id"], kind="sql_statement", source=s, source_lang="Snowflake SQL",
                                         target="one Databricks SQL statement ending with ';'. Snowflake :PARAM binds stay as :PARAM named parameter markers",
                                         instructions=f"Deterministic transpile failed: {e}"))
                origin = Origin.HYBRID.value
        params = "\n".join(f"-- widget/parameter: {a['name']} ({a['type']}) referenced as :{a['name']}" for a in o.get("args", []))
        code = "\n".join(["-- Databricks notebook source", marker("--", o["id"], "PROCEDURE", origin, "SQL notebook"),
                          params, *out])
        return [Fragment(o["id"], "PROCEDURE", "notebook", origin, base + ".sql", code, base, notes=notes)]

    lang = o.get("language", "SQL")
    ph = ctx.slots.new(
        node_id=o["id"], kind="procedure", source=o.get("body", ""), source_lang=f"Snowflake {lang} stored procedure",
        target="PySpark code for a Databricks Python notebook cell (no notebook header, no widget definitions)",
        instructions=(f"Arguments are already Python variables: {', '.join(a['name'] for a in o.get('args', [])) or 'none'}. "
                      f"Return value ({o.get('returns')}) must be passed to dbutils.notebook.exit(str(value)). "
                      "Use spark.sql(...) for SQL and the Databricks table names from the NAME MAP. "
                      "Snowflake snowflake.execute / session.sql calls become spark.sql."))
    code = "\n".join(["# Databricks notebook source", marker("#", o["id"], "PROCEDURE", Origin.AI.value, f"source language {lang}"),
                      *widgets, *reads, "", "# COMMAND ----------", "", ph])
    notes.append(f"INFO|{lang} procedure translated by model; requires human review")
    return [Fragment(o["id"], "PROCEDURE", "notebook", Origin.AI.value, base + ".py", code, base, notes=notes)]


REGISTRY = {"TABLE": map_table, "VIEW": map_view, "DYNAMIC_TABLE": map_dynamic_table, "STREAM": map_stream,
            "TASK": map_task, "PROCEDURE": map_procedure}
